export function presetById(id) {
  return PRESETS.find((p) => p.id === id) || null;
}

// Apply a preset to a store: layout, grade, lettering and panel photos.
// Returns the patch the store should apply.
export function presetPatch(preset) {
  return {
    layout: preset.layout,
    grade: preset.grade,
    title: preset.title,
    caption: preset.caption,
    letterPos: preset.letterPos,
    letterGradient: preset.letterGradient,
    panels: preset.photos.map((photoId) => ({
      photoId,
      shiftX: 0,
      shiftY: 0,
      zoom: 1,
      fit: 'fill',
      flip: false,
      grade: null,
    })),
    selectedPanel: 0,
  };
}
